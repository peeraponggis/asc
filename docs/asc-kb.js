    /* ค้นหาแบบง่ายด้วยคำสำคัญ ให้คะแนนจากชื่อเรื่อง แท็ก และเนื้อหา ตามลำดับน้ำหนัก */
    function search(q, limit) {
        const words = String(q || '').toLowerCase().split(/[\s,]+/).filter(w => w.length > 1);
        if (!words.length) return [];
        const hits = [];
        Object.keys(KB).forEach(id => {
            const a = KB[id];
            const title = a.title.toLowerCase();
            const tags = (a.tags || []).join(' ').toLowerCase();
            const body = a.body.toLowerCase();
            let score = 0;
            words.forEach(w => {
                if (title.indexOf(w) >= 0) score += 6;
                if (tags.indexOf(w) >= 0) score += 4;
                if (body.indexOf(w) >= 0) score += 1;
            });
            if (score > 0) hits.push({ id: id, score: score, article: a });
        });
        hits.sort((x, y) => y.score - x.score);
        return limit ? hits.slice(0, limit) : hits;
    }

