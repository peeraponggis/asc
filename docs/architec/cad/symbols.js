export const blockName = (s) => "ASCA_" + s.id;
/** ตำแหน่งข้อความชื่ออุปกรณ์ (ATTRIB TAG) ทางขวาของสัญลักษณ์ */
export function tagPlace(s) { const b = s.bb; return { p: [b[2] + 1.2, s.real ? 0 : (b[1] + b[3]) / 2 - 1.1], h: s.real ? 150 : 2.4 }; }
const circlePts = (cx, cy, r, n = 32) => { const o = []; for (let i = 0; i < n; i++) { const a = (i / n) * 2 * Math.PI; o.push(cx + r * Math.cos(a), cy + r * Math.sin(a)); } return o; };
const arcPts = (cx, cy, r, a0, a1) => { let span = (((a1 - a0) % 360) + 360) % 360 || 360; const n = Math.max(4, Math.ceil(span / 10)), o = [];
  for (let i = 0; i <= n; i++) { const a = ((a0 + (span * i) / n) * Math.PI) / 180; o.push(cx + r * Math.cos(a), cy + r * Math.sin(a)); } return o; };
const rnd = (v) => Math.round(v * 1e4) / 1e4;
/** ข้อความกึ่งกลาง → [x, y, h, rot, s, col] (มุมซ้ายล่างของบรรทัด แบบที่หน้า CAD ใช้วาด) */
export const centeredText = (x, y, h, s) => [rnd(x - s.length * h * 0.36), rnd(y - h * 0.45), h, 0, s, 256];
/** เส้นแสดงผลในพิกัดของสัญลักษณ์ (จุดฐาน 0,0) — รูปแบบเดียวกับวัตถุในหน้า CAD: d = [[xy…, ปิด, สี, ทึบ?]] · x = ข้อความ */
export function symDisplay(s, tag) {
  const d = [], x = [];
  for (const q of s.prims) {
    const k = q[0];
    if (k === "L") d.push([[q[1], q[2], q[3], q[4]], 0, 256]);
    else if (k === "C") d.push([circlePts(q[1], q[2], q[3]), 1, 256]);
    else if (k === "D") d.push([circlePts(q[1], q[2], q[3], 16), 1, 256, 1]);
    else if (k === "A") d.push([arcPts(q[1], q[2], q[3], q[4], q[5]), 0, 256]);
    else if (k === "R") d.push([[q[1], q[2], q[1] + q[3], q[2], q[1] + q[3], q[2] + q[4], q[1], q[2] + q[4]], 1, 256]);
    else if (k === "T") x.push(centeredText(q[1], q[2], q[3], q[4]));
    else d.push([q.slice(1), k === "P" ? 0 : 1, 256, ...(k === "F" ? [1] : [])]);
  }
  if (tag) { const t = tagPlace(s); x.push([t.p[0], t.p[1], t.h, 0, tag, 256]); }
  return { d, x };
}
/** ชิ้นส่วนใน block (DXF) — layer 0 สี ByBlock (ได้ layer/สีของสัญลักษณ์ที่วาง แบบ AutoCAD) */
export function symMembers(s) {
  const at = { l: "0", c: 0 }, out = [];
  const poly = (f, closed) => { const pts = []; for (let i = 0; i < f.length; i += 2) pts.push([rnd(f[i]), rnd(f[i + 1]), 0]); return { ...at, t: "LWPOLYLINE", g: { pts, closed, w: 0 } }; };
  const solid = (f) => { const pts = []; for (let i = 0; i < f.length; i += 2) pts.push([rnd(f[i]), rnd(f[i + 1])]); return { ...at, t: "HATCH", g: { pts, pattern: "SOLID" } }; };
  for (const q of s.prims) {
    const k = q[0];
    if (k === "L") out.push({ ...at, t: "LINE", g: { a: [q[1], q[2]], b: [q[3], q[4]] } });
    else if (k === "C") out.push({ ...at, t: "CIRCLE", g: { c: [q[1], q[2]], r: q[3] } });
    else if (k === "D") out.push({ ...at, t: "CIRCLE", g: { c: [q[1], q[2]], r: q[3] } }, solid(circlePts(q[1], q[2], q[3], 16)));
    else if (k === "A") out.push({ ...at, t: "ARC", g: { c: [q[1], q[2]], r: q[3], a0: q[4], a1: q[5] } });
    else if (k === "R") out.push(poly([q[1], q[2], q[1] + q[3], q[2], q[1] + q[3], q[2] + q[4], q[1], q[2] + q[4]], true));
    else if (k === "T") out.push({ ...at, t: "TEXT", g: { p: [q[1], q[2]], h: q[3], rot: 0, s: q[4], ha: 1, va: 2 } });
    else if (k === "F") out.push(poly(q.slice(1), true), solid(q.slice(1)));
    else out.push(poly(q.slice(1), k === "Q"));
  }
  return out;
}
/** นิยาม block ที่ส่งให้ server ตอนบันทึก (สร้างครั้งเดียวต่อไฟล์) */
export function blockDef(s) {
  const def = { name: blockName(s), members: symMembers(s) };
  if (s.tag) { const t = tagPlace(s); def.attdef = { tag: "TAG", p: t.p, h: t.h }; }
  return def;
}
const escX = (v) => String(v).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
/** ภาพตัวอย่าง SVG (สีตามตัวอักษร) */
export function symSVG(s, cls) {
  const b = s.bb, w = b[2] - b[0], h = b[3] - b[1], pad = Math.max(w, h) * 0.08 + 0.4, sw = Math.max(w, h) / 34, Y = (y) => -y, out = [];
  for (const q of s.prims) {
    const k = q[0];
    if (k === "L") out.push(`<line x1="${q[1]}" y1="${Y(q[2])}" x2="${q[3]}" y2="${Y(q[4])}"/>`);
    else if (k === "C") out.push(`<circle cx="${q[1]}" cy="${Y(q[2])}" r="${q[3]}"/>`);
    else if (k === "D") out.push(`<circle cx="${q[1]}" cy="${Y(q[2])}" r="${q[3]}" fill="currentColor"/>`);
    else if (k === "A") {
      const r = Math.PI / 180, p0 = [q[1] + q[3] * Math.cos(q[4] * r), q[2] + q[3] * Math.sin(q[4] * r)], p1 = [q[1] + q[3] * Math.cos(q[5] * r), q[2] + q[3] * Math.sin(q[5] * r)];
      out.push(`<path d="M${rnd(p0[0])} ${rnd(Y(p0[1]))}A${q[3]} ${q[3]} 0 ${q[5] - q[4] > 180 ? 1 : 0} 0 ${rnd(p1[0])} ${rnd(Y(p1[1]))}"/>`);
    } else if (k === "R") out.push(`<rect x="${q[1]}" y="${Y(q[2] + q[4])}" width="${q[3]}" height="${q[4]}"/>`);
    else if (k === "T") out.push(`<text x="${q[1]}" y="${Y(q[2])}" font-size="${q[3]}" text-anchor="middle" dominant-baseline="central" fill="currentColor" stroke="none" font-family="Tahoma, sans-serif">${escX(q[4])}</text>`);
    else { const pts = []; for (let i = 1; i < q.length; i += 2) pts.push(q[i] + "," + Y(q[i + 1])); out.push(`<${k === "P" ? "polyline" : "polygon"} points="${pts.join(" ")}"${k === "F" ? ' fill="currentColor"' : ""}/>`); }
  }
  return `<svg class="${cls || ""}" viewBox="${rnd(b[0] - pad)} ${rnd(-b[3] - pad)} ${rnd(w + 2 * pad)} ${rnd(h + 2 * pad)}" fill="none" stroke="currentColor" stroke-width="${rnd(sw)}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${out.join("")}</svg>`;
}
