export function parseSym(src) {
  return src.split(";").map((s) => s.trim()).filter(Boolean).map((s) => {
    const k = s[0], rest = s.slice(1).trim();
    if (k === "T") { const m = rest.match(/^(\S+)\s+(\S+)\s+(\S+)\s+(.+)$/); return ["T", +m[1], +m[2], +m[3], m[4]]; }
    return [k, ...rest.split(/[\s,]+/).map(Number)];
  });
}
export function primBox(prims) {
  const b = [1e9, 1e9, -1e9, -1e9], add = (x, y) => { b[0] = Math.min(b[0], x); b[1] = Math.min(b[1], y); b[2] = Math.max(b[2], x); b[3] = Math.max(b[3], y); };
  for (const q of prims) {
    const k = q[0];
    if (k === "L") { add(q[1], q[2]); add(q[3], q[4]); }
    else if (k === "C" || k === "D" || k === "A") { add(q[1] - q[3], q[2] - q[3]); add(q[1] + q[3], q[2] + q[3]); }
    else if (k === "R") { add(q[1], q[2]); add(q[1] + q[3], q[2] + q[4]); }
    else if (k === "T") { const w = q[4].length * q[3] * 0.32; add(q[1] - w, q[2] - q[3] / 2); add(q[1] + w, q[2] + q[3] / 2); }
    else for (let i = 1; i < q.length; i += 2) add(q[i], q[i + 1]);
  }
  return b;
}
